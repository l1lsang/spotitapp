// Builds src/lib/book/glyphCoverage.ts: which characters each book font can draw.
//   node scripts/build-book-glyphs.mjs           write the file
//   node scripts/build-book-glyphs.mjs --check   fail if it is out of date
// Gowun Batang is read from the app's subset, not the full font: a character missing
// there falls back in the app, so print must fall back for it too.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { fontCodePoints, toRanges } from './fontCmap.mjs'

const root = new URL('..', import.meta.url)
export const FONT_FILES = {
  pretendard: 'assets/fonts/Pretendard-Regular.otf',
  'gowun-batang': 'assets/fonts/book/GowunBatang-Regular.ttf',
  'nanum-pen': 'assets/fonts/book/NanumPenScript-Regular.ttf',
}
export const OUTPUT = 'src/lib/book/glyphCoverage.ts'

/** Ranges as base-36 "gap.length" pairs: gap from the previous range's end, then size - 1. */
export function encodeRanges(ranges) {
  let previous = -1
  return ranges.map(([first, last]) => {
    const token = `${(first - previous - 1).toString(36)}.${(last - first).toString(36)}`
    previous = last
    return token
  }).join(',')
}

export function renderCoverageModule() {
  const lines = Object.entries(FONT_FILES).map(([id, file]) => {
    const codes = fontCodePoints(readFileSync(new URL(file, root)))
    return `  // ${file}: ${codes.size} characters\n  '${id}': '${encodeRanges(toRanges(codes))}',`
  })
  return [
    '// Generated by scripts/build-book-glyphs.mjs from the font files. Do not edit by hand:',
    '// change the fonts, then run `node scripts/build-book-glyphs.mjs`.',
    "import type { BookFontId } from '../../types/book'",
    '',
    '/** Characters each font maps to a glyph, as encoded ranges (see `glyphs.ts`). */',
    'export const GLYPH_COVERAGE: Record<BookFontId, string> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = new URL(OUTPUT, root)
  const next = renderCoverageModule()
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n')
    if (current !== next) { console.error(`${OUTPUT} is out of date: run node scripts/build-book-glyphs.mjs`); process.exit(1) }
    console.log(`${OUTPUT} is up to date`)
  } else {
    writeFileSync(target, next)
    console.log(`wrote ${OUTPUT}`)
  }
}
